export const getConversionById = (id: string): ConversionDefinition | undefined => {
  return CONVERSIONS.find(c => c.id === id);
};

export const getConversionsByCategory = (categoryId: string): ConversionDefinition[] => {
  return CONVERSIONS.filter(c => c.category === categoryId);
};

export const findConversionForFile = (filename: string): ConversionDefinition[] => {
  const ext = '.' + filename.split('.').pop()?.toLowerCase();
  return CONVERSIONS.filter(c => c.acceptsExtensions.some(e => e.toLowerCase() === ext));
};

export const validateFileForConversion = (
  file: File, 
  conversion: ConversionDefinition
): { isValid: boolean; error?: string } => {
  const ext = '.' + file.name.split('.').pop()?.toLowerCase();
  const isExtAccepted = conversion.acceptsExtensions.some(e => {
    if (e.startsWith('.')) return e.toLowerCase() === ext;
    return file.name.toLowerCase().endsWith(e.toLowerCase());
  });

  if (!isExtAccepted && !conversion.acceptsMimeTypes.includes('image/*') && !conversion.acceptsMimeTypes.includes(file.type)) {
    return {
      isValid: false,
      error: `Unsupported file format "${file.name}". Accepted formats for ${conversion.name} are: ${conversion.acceptsExtensions.join(', ')}`,
    };
  }

  // File size limit: 100MB
  const maxBytes = 100 * 1024 * 1024;
  if (file.size > maxBytes) {
    return {
      isValid: false,
      error: `File is too large (${(file.size / (1024 * 1024)).toFixed(1)} MB). Maximum allowed size is 100 MB.`,
    };
  }

  return { isValid: true };
};

